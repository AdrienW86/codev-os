// Conversion PURE d'une analyse Google Ads enregistrée en propositions de diagnostic.
// Aucun texte libre n'est pris pour une preuve et aucune action n'est exécutée.
export type LiveAdsPriority = {
  title: string;
  priority: "high" | "medium" | "low";
  source: "ads";
  origin: "diagnostic";
  detail: string;
  evidence: string[];
  href: string;
  date: string;
};

const actionLabels: Record<string, string> = {
  verify_tracking: "Vérifier le suivi des conversions",
  review_geography: "Contrôler les zones ciblées",
  review_services: "Examiner les services ciblés",
  review_schedule: "Examiner les horaires de diffusion",
  review_budget: "Examiner le budget",
  review_landing_page: "Examiner la page de destination",
  review_capacity: "Vérifier la capacité à traiter les prospects",
};
const rank: Record<LiveAdsPriority["priority"], number> = { high: 0, medium: 1, low: 2 };
const record = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === "object" && !Array.isArray(value);
const text = (value: unknown, limit = 500): string =>
  typeof value === "string" ? value.trim().slice(0, limit) : "";
const campaignId = (value: unknown): value is string =>
  typeof value === "string" && /^\d{1,20}$/.test(value);

/**
 * AI outputs have been validated against the campaign/evidence ledger by
 * validateAdsAIOutput BEFORE storage. We recheck IDs at read time and require
 * campaign-specific proofs to avoid resurrecting ungrounded historical output.
 * Deterministic findings are generated by buildAdsFindings from API metrics.
 */
export function extractLiveAdsPriorities(metadata: unknown, runId: string, fetchedAt: string): LiveAdsPriority[] {
  if (!record(metadata) || metadata.run_type !== "google_ads_read_only"
    || !/^[\da-f]{8}-[\da-f]{4}-[\da-f]{4}-[\da-f]{4}-[\da-f]{12}$/i.test(runId)) return [];
  const scope = metadata.scope;
  if (!record(scope) || !Array.isArray(scope.campaignIds) || !record(scope.campaignNames)) return [];
  const allowed = new Set(scope.campaignIds.filter(campaignId));
  if (!allowed.size) return [];
  const names = scope.campaignNames;
  const href = "/advertising/analyses/" + runId;
  const date = text(fetchedAt, 40);
  const candidates: LiveAdsPriority[] = [];

  if (metadata.engine === "ai" && record(metadata.analysis) && Array.isArray(metadata.analysis.recommendations)
    && Array.isArray(metadata.evidence)) {
    const ledger = new Map<string, { campaignId: string | null; text: string }>();
    for (const raw of metadata.evidence) {
      if (!record(raw)) continue;
      const id = text(raw.id, 100);
      const campaign = raw.campaignId;
      if (!id || !(campaign === null || campaignId(campaign) && allowed.has(campaign))) continue;
      const statement = text(raw.text, 400);
      if (statement) ledger.set(id, { campaignId: campaign as string | null, text: statement });
    }
    for (const raw of metadata.analysis.recommendations.slice(0, 5)) {
      if (!record(raw) || !Object.hasOwn(actionLabels, String(raw.action))
        || !Object.hasOwn(rank, String(raw.priority))
        || !Array.isArray(raw.campaignIds) || !raw.campaignIds.length
        || raw.campaignIds.some((id: unknown) => !campaignId(id) || !allowed.has(id))
        || !Array.isArray(raw.evidenceIds)) continue;
      const ids = raw.campaignIds as string[];
      const proofs = raw.evidenceIds.map((id: unknown) => ledger.get(String(id))).filter(
        (item): item is { campaignId: string | null; text: string } => Boolean(item && (item.campaignId === null || ids.includes(item.campaignId))),
      );
      if (!proofs.length || !proofs.some((item) => item.campaignId !== null)
        || proofs.length !== raw.evidenceIds.length) continue;
      const rationale = text(raw.rationale, 600);
      if (!rationale) continue;
      const campaignNames = ids.slice(0, 2).map((id) => text(names[id], 80) || id);
      candidates.push({
        title: actionLabels[String(raw.action)] + " — " + campaignNames.join(", "),
        priority: raw.priority as LiveAdsPriority["priority"],
        source: "ads", origin: "diagnostic", detail: rationale,
        evidence: proofs.map((item) => item.text).slice(0, 4), href, date,
      });
    }
  }
  // In case the AI output contains fewer than three grounded actions, supplement
  // with independently computed, auditable deterministic checks.
  if (Array.isArray(metadata.findings)) {
    for (const finding of metadata.findings.slice(0, 50)) {
      if (!record(finding) || !campaignId(finding.campaignId) || !allowed.has(finding.campaignId)
        || !Object.hasOwn(rank, String(finding.priority))
        || !Array.isArray(finding.evidence)) continue;
      const title = text(finding.title, 160);
      const detail = text(finding.nextStep, 550);
      const evidence = finding.evidence.map((item: unknown) => text(item, 300)).filter(Boolean).slice(0, 4);
      if (!title || !detail || !evidence.length) continue;
      candidates.push({
        title: title + " — " + (text(names[finding.campaignId], 80) || finding.campaignId),
        priority: finding.priority as LiveAdsPriority["priority"],
        source: "ads", origin: "diagnostic", detail, evidence, href, date,
      });
    }
  }
  const seen = new Set<string>();
  return candidates.sort((a, b) => rank[a.priority] - rank[b.priority]).filter((candidate) => {
    const key = candidate.title.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  }).slice(0, 3);
}
